#!/usr/bin/env python3
"""Write the coord_dto test vectors with the server's own encoder.

Usage: python3 tools/gen_coord_dto_vectors.py <path to the PluTO repo>

Each line of components/coord_dto/test_host/coord_dto_vectors.txt is a payload
from PluTO's server_core/coord_dto.py plus the fields it was built from, and
the host test decodes it with the real decoder. The file is committed so CI
does not need the PluTO repo: rerun this when the encoder changes.
"""
import sys
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / 'components/coord_dto/test_host/coord_dto_vectors.txt'

# The instants of the worked example (§7).
T0_MS = 1789763400000
T_SENT_MS = 1789763398000

HEADER = """\
# Generated by tools/gen_coord_dto_vectors.py from PluTO's encoder; do not edit by hand.
# name payload_hex flags count t0_ms t_sent_ms, then dt_ms az_cdeg el_cdeg per point
"""


def vectors(dto):
    """(name, payload, flags, t0_ms, points) for each case, points as (dt_ms, az_cdeg, el_cdeg)."""
    worked = [(0, 12345, 4500), (1000, 12400, 4530), (2000, 12455, 4560)]
    one = [(0, 18000, 0)]
    edges = [(0, 0, -9000), (1, 35999, 9000), (0xFFFFFFFF, 18000, 0)]
    full = [(1000 * i, 2250 * i, 600 * i - 4500) for i in range(dto.MAX_POINTS)]
    # A 1 Hz pass across north, through the server's real path: degrees in,
    # batch planned. 359.995° must round to 0, not to 36000 (§7.1).
    north = dto.plan_batches(
        [(T0_MS + 1000 * i, az, 20.0 + i) for i, az in enumerate((359.98, 359.99, 359.995, 0.004, 0.01))]
    )[0]

    return [
        ('worked_example', dto.encode(T0_MS, T_SENT_MS, worked), 0, T0_MS, worked),
        ('hold', dto.encode_hold(T_SENT_MS), dto.FLAG_HOLD, T_SENT_MS, []),
        ('one_point', dto.encode(T0_MS, T_SENT_MS, one), 0, T0_MS, one),
        ('range_edges', dto.encode(T0_MS, T_SENT_MS, edges), 0, T0_MS, edges),
        ('max_count', dto.encode(T0_MS, T_SENT_MS, full), 0, T0_MS, full),
        ('north_crossing', north.encode(T_SENT_MS), 0, north.t0_ms, list(north.points)),
    ]


def main():
    if len(sys.argv) != 2:
        sys.exit(f'usage: {sys.argv[0]} <path to the PluTO repo>')

    # coord_dto.py uses only the standard library and server_core/__init__.py is
    # empty, so this import does not need Django.
    sys.path.insert(0, sys.argv[1])
    from server_core import coord_dto

    lines = []
    for name, payload, flags, t0_ms, points in vectors(coord_dto):
        fields = [name, payload.hex(), flags, len(points), t0_ms, T_SENT_MS]
        fields += [value for point in points for value in point]
        lines.append(' '.join(str(field) for field in fields))
    OUTPUT.write_text(HEADER + '\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
